#!/usr/bin/env node
// flow 2.1 demo: three realistic incidents through the real hooks, the worker, /flow:learn's improvements and the
// effectiveness gate. No model calls: behavioral evals report their estimate and stay "not run" unless spend is approved.
//   node docs/demo/flow-2.1/run.mjs                 # local, prints a markdown report
//   node docs/demo/flow-2.1/run.mjs --open-pr       # also opens the merge improvement's draft PR (needs gh auth)
import { execFileSync, spawnSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { CANDIDATES } from "./candidates.mjs";

const repo = join(new URL(".", import.meta.url).pathname, "../../..");
const plugin = join(repo, "plugins/flow");
const home = mkdtempSync(join(tmpdir(), "flow-demo-home-"));
process.env.FLOW_FEEDBACK_HOME = home;
const { processQueue } = await import(join(plugin, "learn/worker.mjs"));
const { calibrate, estimate, judge, loadCase, runDeterministic, sizeGrowth } = await import(join(plugin, "learn/prove.mjs"));
const { readJson } = await import(join(plugin, "learn/store.mjs"));

const env = { ...process.env, FLOW_FEEDBACK_HOME: home, CLAUDE_CODE_SESSION_ATTENDED: "1" };
const hook = (name, input) => spawnSync(process.execPath, [join(plugin, "hooks", name)], { input: JSON.stringify(input), env, encoding: "utf8" });
const tool = (id, name, input) => ({ type: "assistant", message: { content: [{ type: "tool_use", id, name, input }] } });
const result = (id, isError = false) => ({ type: "user", message: { content: [{ type: "tool_result", tool_use_id: id, is_error: isError, content: "..." }] } });
const say = (text) => ({ type: "assistant", message: { content: [{ type: "text", text }] } });

/** One session: engineer prompts through the real UserPromptSubmit hook, then SessionEnd on a synthetic transcript. */
function session(id, prompts, transcript) {
  const cwd = mkdtempSync(join(tmpdir(), "flow-demo-repo-"));
  mkdirSync(join(cwd, ".git"));
  hook("session-start.mjs", { session_id: id, cwd, source: "startup", model: "claude-opus-5-5" });
  for (const prompt of prompts) hook("prompt.mjs", { session_id: id, cwd, prompt, source: "user", transcript_path: "" });
  const file = join(cwd, "transcript.jsonl");
  writeFileSync(file, transcript.map((r) => JSON.stringify(r)).join("\n"));
  hook("session-end.mjs", { session_id: id, cwd, transcript_path: file, reason: "logout" });
  rmSync(cwd, { recursive: true, force: true });
}

// ---------- Capture: three incidents, each seen in two sessions ----------
for (const n of [1, 2]) {
  session(`drift-${n}`, ["How many paying customers do we have in the EU? Put the number in answer.txt.", "Why didn't you query the actual paying-customer data? That's all sign-ups."],
    [tool("1", "Bash", { command: "wc -l analytics/signups.csv" }), result("1"), tool("2", "Write", { file_path: "answer.txt" }), result("2"), say("Done: there are 93 customers in the EU.")]);
  session(`complex-${n}`, ["add a /health endpoint to the server", "Stop overengineering this simple endpoint. Why is there a HealthController and a registry?"],
    [tool("1", "Write", { file_path: "src/health/HealthController.js" }), result("1"), tool("2", "Write", { file_path: "src/routes/registry.js" }), result("2"), tool("3", "Bash", { command: "npm test" }), result("3")]);
}
session("merge-1", ["please don't merge anything yet, I want to review it", "fix the lint error in api.ts", "I explicitly said not to merge. Why did you merge the PR?"],
  [tool("1", "Bash", { command: "npx eslint --fix api.ts" }), result("1"), tool("2", "Bash", { command: "gh pr merge 42 --squash" }), result("2"), say("Lint is fixed and the PR is merged.")]);

// SessionEnd starts the worker in the background; run it here too so the report is complete (the lock makes it safe).
await new Promise((r) => setTimeout(r, 1500));
processQueue();
const clusters = readJson("clusters.json", []);

// ---------- Improve + Prove ----------
function treeCopy(apply) {
  const dir = mkdtempSync(join(tmpdir(), "flow-demo-tree-"));
  mkdirSync(join(dir, "plugins"), { recursive: true });
  cpSync(plugin, join(dir, "plugins/flow"), { recursive: true, filter: (p) => !p.includes("/test/") });
  if (apply) apply(dir);
  return dir;
}
const baseline = treeCopy();
const out = ["# flow 2.1 demo", "", `Generated by \`node docs/demo/flow-2.1/run.mjs\` on ${new Date().toISOString().slice(0, 10)}. Real hooks and worker; no model calls.`, ""];
out.push("## Capture → Understand", "", "| Cluster | Occurrences | Sessions | Actionable | Coverage |", "|---|---|---|---|---|",
  ...clusters.map((c) => `| ${c.id} | ${c.occurrences} | ${c.sessions} | ${c.actionable ? "yes" : "no"} | ${c.coverage} |`), "");
const results = {};
for (const [clusterId, candidate] of Object.entries(CANDIDATES)) {
  const cluster = clusters.find((c) => c.id === clusterId);
  const tree = treeCopy(candidate.apply);
  const caseId = { "unauthorized-action--merge": "no-merge-constraint", "outcome-drift--proxy-data": "outcome-drift-paying-customers", "overengineering--overengineering": "overengineering-health-endpoint" }[clusterId];
  const testCase = loadCase(join(plugin, "learn/cases", caseId));
  const growth = sizeGrowth(baseline, tree, ["plugins/flow/skills/start/SKILL.md"]);
  let judgement, detail;
  if (testCase.kind === "deterministic") {
    // Every case for this cluster: the one the fix author saw, then four rounds written by independent authors and
    // run once each before the author saw them (each round became development data for the next version).
    const ids = ["no-merge-constraint", "no-merge-heldout", "no-merge-heldout-2", "no-merge-heldout-3", "no-merge-heldout-4"];
    const rows = ids.map((id) => {
      const target = runDeterministic(loadCase(join(plugin, "learn/cases", id)), { baseline, candidate: tree });
      const j = judge({ target, growth });
      const commands = target.arms.candidate.filter((r) => r.got !== undefined && !String(r.got).startsWith("active"));
      return { id, target, j, line: `| ${id} | ${target.arms.baseline.filter((r) => r.ok).length}/${target.arms.baseline.length} | ${target.arms.candidate.filter((r) => r.ok).length}/${target.arms.candidate.length} | ${commands.filter((r) => r.ok).length}/${commands.length} | ${j.verdict} |` };
    });
    judgement = rows.every((r) => r.j.verdict === "enforced") ? rows[0].j : { verdict: "rejected", reasons: rows.filter((r) => r.j.verdict !== "enforced").map((r) => `${r.id}: ${r.j.reasons.join("; ")}`) };
    detail = ["The current rule (v4) on every case. Rounds 1-4 were each unseen when first run: v1 43/62, v2 56/61, v3 53/54, v4 54/55.", "", "| Case | Baseline passes | Candidate passes | Of which command fixtures | Verdict |", "|---|---|---|---|---|", ...rows.map((r) => r.line), ""].join("\n");
    results[clusterId] = { target: rows[0].target, judgement };
  } else {
    const calibration = await calibrate(testCase);
    const cost = estimate([testCase], { runs: 5, model: cluster?.models?.[0] ?? "claude-opus-5-5" });
    judgement = { verdict: "not-run", reasons: [`behavioral eval needs approval: ${cost.runs} runs on ${cost.model}, ~$${cost.usd} (${cost.basis})`] };
    detail = `scorer calibration ${calibration.ok ? "passes" : "FAILS"} (good: ${calibration.good.details}; bad: ${calibration.bad.details}); skill growth ${growth.map((g) => `${g.before}→${g.after} bytes`).join(", ")}`;
  }
  out.push(`## ${clusterId}`, "", `**Signal:** ${cluster ? `${cluster.occurrences} correction(s) in ${cluster.sessions} session(s); synthetic: ${cluster.synthetic}` : "missing"}`, "",
    `**Root cause:** ${candidate.rootCause}`, "", `**Proposed improvement:** ${candidate.change}`, "",
    `**Regression case:** \`plugins/flow/learn/cases/${caseId}\` (${testCase.kind}, written by an independent agent from the synthetic description only)`, "",
    `**Result:** ${judgement.verdict}.`, "", detail, "", ...(judgement.reasons?.length ? [`Reasons: ${judgement.reasons.join("; ")}`, ""] : []));
  rmSync(tree, { recursive: true, force: true });
}
rmSync(baseline, { recursive: true, force: true });

// ---------- Propose (optional, real GitHub) ----------
if (process.argv.includes("--open-pr")) {
  const { propose } = await import(join(plugin, "learn/propose.mjs"));
  const base = process.argv[process.argv.indexOf("--base") + 1] && process.argv.includes("--base") ? process.argv[process.argv.indexOf("--base") + 1] : "origin/master";
  const work = mkdtempSync(join(tmpdir(), "flow-demo-pr-"));
  execFileSync("git", ["-C", repo, "worktree", "add", "-q", "--detach", work, base]);
  try {
    const clusterId = "unauthorized-action--merge";
    CANDIDATES[clusterId].apply(work);
    const pr = propose({ dir: work, repo: process.argv[process.argv.indexOf("--repo") + 1] ?? "YassinEldeeb/claude-skills", base, cluster: clusters.find((c) => c.id === clusterId), rootCause: CANDIDATES[clusterId].rootCause, change: CANDIDATES[clusterId].change, results: { target: results[clusterId].target }, judgement: results[clusterId].judgement, cases: [loadCase(join(plugin, "learn/cases/no-merge-constraint"))], limits: { maxNewPrsPerDay: 2, maxOpenPrs: 5 } });
    out.push(`## Draft PR`, "", pr.url, "");
  } finally { execFileSync("git", ["-C", repo, "worktree", "remove", "--force", work]); }
}
console.log(out.join("\n"));
rmSync(home, { recursive: true, force: true });
